def section_gap(data: dict) -> dict:
    rows = list(csv.DictReader(GAP_CSV.open(encoding="utf-8")))
    ind = ["stunted", "wasted", "underweight"]
    out_rows, india = [], None
    for r in rows:
        item = {"state": r["state"], "nfhs5": {k: float(r[f"nfhs5_{k}_pct"]) for k in ind},
                "pt": {k: float(r[f"pt_jun2025_{k}_pct"]) for k in ind}}
        if r["state"] == "India":
            india = item
        else:
            out_rows.append(item)
    counts = {k: {"pt_lower": sum(x["pt"][k] < x["nfhs5"][k] for x in out_rows), "n": len(out_rows)} for k in ind}
    assert counts["wasted"] == {"pt_lower": 36, "n": 36}, counts["wasted"]
    assert india["nfhs5"]["wasted"] == 19.3 and india["pt"]["wasted"] == 5.46
    return {
        "label": "REAL", "rows": out_rows, "india": india, "counts": counts,
        "source_file": "research/sources/state_gap_verified.csv (notes: research/sources/V4-state-gap-verified.md)",
        "nfhs5_source": rows[0]["nfhs5_source"].split(": http")[0],
        "pt_source": rows[0]["pt_source"].split(": http")[0],
        "caveat": ("Different periods (2019-21 vs June 2025), age bands (0-59 months vs 0-5 years) and denominators "
                   "(household sample vs registered and measured children): an unexplained discrepancy, not a "
                   "measured under-detection rate."),
    }


