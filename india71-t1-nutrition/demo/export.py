def _alerts_for(example_cohort: dict):
    from architecture.contracts import models as m
    df23, _ = build23()
    sim = sim23()
    awc, month = example_cohort["example"]["awc"], example_cohort["example"]["month_index"]
    g = sim["geo"].set_index("awc_code").loc[awc]
    geo = m.GeoUnit(state_code=g.state_code, district_code=g.district_code, project_code=g.project_code,
                    sector_code=g.sector_code, awc_code=awc)
    cur = df23[(df23.awc_code == awc) & (df23.month_index == month)]
    pool = rank_pool(df23)
    pool = pool[(pool.awc_code == awc) & (pool.month_index == month)]
    today = pd.Timestamp(cur.measured_on.max()).date()
    alerts = []
    for r in cur[cur.obs_status.isin(["sam", "mam"])].itertuples():
        kind = m.AlertKind.SAM if r.obs_status == "sam" else m.AlertKind.MAM
        alerts.append(m.Alert(alert_id=f"{kind.value}-{r.event_id}", child_key=r.child_key, geo=geo, kind=kind,
                              severity=4 if r.obs_status == "sam" else 3, created_on=today,
                              evidence=[f"WHZ {r.wlhz:.2f}" if pd.notna(r.wlhz) else "MUAC/oedema"],
                              recommended_action="protocol", synthetic=True))
    for r in pool[pool.rank_whz <= 5].sort_values("rank_whz").itertuples():
        alerts.append(m.Alert(alert_id=f"risk_high-{r.event_id}", child_key=r.child_key, geo=geo, kind=m.AlertKind.RISK_HIGH,
                              severity=2, created_on=today, evidence=[f"WHZ {r.wlhz:.2f} (rank {int(r.rank_whz)} in AWC)"],
                              recommended_action="home visit", synthetic=True))
    return geo, today, alerts


