def ledger_scenarios(entries: list[dict], checkpoint: tuple[int, str], k: int) -> dict:
    from architecture.contracts.models import AuditEntry
    from components.audit_ledger.ledger import Ledger, _hash_entry

    def verdict(es: list[dict], cp=None) -> list:
        ok, bad = Ledger([AuditEntry.model_validate(e) for e in es]).verify(cp)
        return [bool(ok), bad]

    def flip(es):
        es = [dict(e) for e in es]
        es[k]["action"] = "access_allow"
        return es

    def reseal(es, start, stop=None):
        es = [dict(e) for e in es]
        for i in range(start, len(es) if stop is None else stop):
            if i > start:
                es[i]["prev_hash"] = es[i - 1]["hash"]
            es[i]["hash"] = _hash_entry(AuditEntry.model_validate(es[i]))
        return es

    cp = list(checkpoint)
    return {
        "intact": {"no_checkpoint": verdict(entries), "checkpoint": verdict(entries, checkpoint)},
        "flip": {"no_checkpoint": verdict(flip(entries)), "checkpoint": verdict(flip(entries), checkpoint)},
        "flip_reseal_one": {"no_checkpoint": verdict(reseal(flip(entries), k, k + 1)),
                            "checkpoint": verdict(reseal(flip(entries), k, k + 1), checkpoint)},
        "flip_reseal_all": {"no_checkpoint": verdict(reseal(flip(entries), k)),
                            "checkpoint": verdict(reseal(flip(entries), k), checkpoint)},
        "truncate_3": {"no_checkpoint": verdict(entries[:-3]), "checkpoint": verdict(entries[:-3], checkpoint)},
        "checkpoint": cp, "flip_index": k,
    }


