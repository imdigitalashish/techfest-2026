def cached(name: str, fn):
    CACHE.mkdir(parents=True, exist_ok=True)
    path = CACHE / f"{name}.pkl"
    if path.exists():
        with path.open("rb") as f:
            return pickle.load(f)
    memory_guard()
    value = fn()
    with path.open("wb") as f:
        pickle.dump(value, f)
    return value


