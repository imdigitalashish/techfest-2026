def _strip(x):
    if isinstance(x, dict):
        return {k: _strip(v) for k, v in x.items() if k not in VOLATILE}
    if isinstance(x, list):
        return [_strip(v) for v in x]
    return x


def check_quick(data: dict) -> list[str]:
    """Cheap re-derivations (about a minute) against the committed data file."""
    from architecture.contracts.models import AuditEntry
    from components.audit_ledger.ledger import Ledger
    errors = []

    def same(name: str, a, b):
        if _strip(a) != _strip(b):
            errors.append(f"{name}: re-derived value differs from demo_data.js")
        else:
            print(f"  ok  {name}")

    same("gap (state_gap_verified.csv)", section_gap(data), data["gap"])
    if DISTRICT_CSV.exists():
        same("districts (nfhs5_district_tidy.csv)", section_districts(data), data["districts"])
    else:
        print("  skip districts: .data/raw/nfhs5 missing (run eval/fetch_nfhs5.py)")
    same("committed eval/results", section_committed(data), data["committed"])
    cell = _grid_cell((0.35, 0.0))
    check_default_cell(cell, data["committed"]["identity_linkage"])
    same("linkage default cell (re-run through the encoded boundary, == identity_linkage.json)", cell,
         data["linkage"]["cells"][data["linkage"]["default"]])
    for pid in data["sim"]["order"]:
        led = data["sim"][pid]["ledger"]
        cp = (led["checkpoint"]["count"], led["checkpoint"]["head"])
        ok, bad = Ledger([AuditEntry.model_validate(e) for e in led["entries"]]).verify(cp)
        if not ok:
            errors.append(f"ledger[{pid}]: exported chain fails Python verify at {bad}")
        scen = ledger_scenarios(led["entries"], cp, led["python_verdicts"]["flip_index"])
        same(f"ledger[{pid}] chain + tamper verdicts (Python)", json.loads(json.dumps(scen)), led["python_verdicts"])
        cal = data["sim"][pid]["calibration"]
        pre = data["districts"]["presets"][pid]
        if cal["target_pct"]["wasted"] != pre["wasted"] or cal["target_pct"]["stunted"] != pre["stunted"]:
            errors.append(f"sim[{pid}]: calibration targets differ from the REAL district values")
    return errors


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--only", default="", help=f"comma-separated subset of {','.join(SECTIONS)}")
    ap.add_argument("--districts", default=",".join(PRESETS), help="preset districts for the sim section")
    ap.add_argument("--workers", type=int, default=2, help="processes for the linkage grid (default 2)")
    ap.add_argument("--check", action="store_true", help="quick re-derivation against demo_data.js")
    args = ap.parse_args()
    if os.nice(0) < 10:
        os.nice(10 - os.nice(0))
    data = read_data()
    if args.check:
        errors = check_quick(data)
        for e in errors:
            print("FAIL", e)
        print("export --check:", "FAILED" if errors else "all re-derived values match")
        return 1 if errors else 0
    only = [s for s in args.only.split(",") if s] or SECTIONS
    unknown = set(only) - set(SECTIONS)
    if unknown:
        ap.error(f"unknown sections {sorted(unknown)}")
    for s in SECTIONS:
        if s not in only:
            continue
        t0 = time.time()
        log(f"section {s} ...")
        if s == "linkage":
            data[s] = section_linkage(data, args.workers)
        elif s == "sim":
            data[s] = section_sim(data, [d for d in args.districts.split(",") if d])
        else:
            data[s] = globals()[f"section_{s}"](data)
        data["meta"] = {"generated_at": datetime.now(timezone(timedelta(hours=5, minutes=30))).strftime("%Y-%m-%d %H:%M IST"),
                        "git_head": git_head(), "exporter": "demo/export.py",
                        "sections": [k for k in SECTIONS if k in data]}
        for stale in [k for k in data if k not in SECTIONS + ["meta"]]:
            data.pop(stale)
        write_data(data)
        log(f"section {s} done in {time.time() - t0:.0f} s -> {DATA_JS.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
