def _strip(x):
    if isinstance(x, dict):
        return {k: _strip(v) for k, v in x.items() if k not in VOLATILE}
    if isinstance(x, list):
        return [_strip(v) for v in x]
    return x


def check_quick(data: dict) -> list[str]:
    """Cheap re-derivations (about a minute) against the committed data file."""
    errors = []

    def same(name: str, a, b):
        if _strip(a) != _strip(b):
            errors.append(f"{name}: re-derived value differs from demo_data.js")
        else:
            print(f"  ok  {name}")

    same("gap", section_gap(data), data["gap"])
    same("committed", section_committed(data), data["committed"])
    cell = _grid_cell((0.35, 0.0))
    check_default_cell(cell, data["committed"]["identity_linkage"])
    same("linkage default cell", cell, data["linkage"]["cells"][data["linkage"]["default"]])
    from architecture.contracts.models import AuditEntry
    from components.audit_ledger.ledger import Ledger
    led = data["ledger"]
    ok, bad = Ledger([AuditEntry.model_validate(e) for e in led["entries"]]).verify(
        (led["checkpoint"]["count"], led["checkpoint"]["head"]))
    if not ok:
        errors.append(f"ledger: exported chain fails Python verify at {bad}")
    else:
        print("  ok  ledger chain verifies in Python")
    scen = ledger_scenarios(led["entries"], (led["checkpoint"]["count"], led["checkpoint"]["head"]),
                            led["python_verdicts"]["flip_index"])
    if json.loads(json.dumps(scen)) != led["python_verdicts"]:
        errors.append("ledger tamper verdicts differ")
    else:
        print("  ok  ledger tamper verdicts")
    return errors


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--only", default="", help=f"comma-separated subset of {','.join(SECTIONS)}")
    ap.add_argument("--workers", type=int, default=2, help="processes for the linkage grid (default 2)")
    ap.add_argument("--check", action="store_true", help="quick re-derivation against demo_data.js")
    ap.add_argument("--check-full", action="store_true", help="re-derive every section and compare")
    args = ap.parse_args()
    if os.nice(0) < 10:
        os.nice(10 - os.nice(0))
    data = read_data()
    if args.check:
        errors = check_quick(data)
        for e in errors:
            print("FAIL", e)
        print("export --check:", "FAILED" if errors else "all re-derived values match")
        return 1 if errors else 0
    if args.check_full:
        fresh = dict(data)
        errors = []
        for s in SECTIONS:
            fresh[s] = RUNNERS[s](fresh, args.workers) if s == "linkage" else RUNNERS[s](fresh)
            if s not in ("ledger",) and _strip(fresh[s]) != _strip(data.get(s)):
                errors.append(s)
            print(f"  {'ok ' if s not in errors else 'FAIL'} {s}")
        print("export --check-full:", "FAILED " + ",".join(errors) if errors else "all sections match")
        return 1 if errors else 0
    only = [s for s in args.only.split(",") if s] or SECTIONS
    unknown = set(only) - set(SECTIONS)
    if unknown:
        ap.error(f"unknown sections {sorted(unknown)}")
    for s in SECTIONS:
        if s not in only:
            continue
        t0 = time.time()
        log(f"section {s} ...")
        data[s] = RUNNERS[s](data, args.workers) if s == "linkage" else RUNNERS[s](data)
        data["meta"] = {"generated_at": datetime.now(timezone(timedelta(hours=5, minutes=30))).strftime("%Y-%m-%d %H:%M IST"),
                        "git_head": git_head(), "exporter": "demo/export.py",
                        "sections": sorted(k for k in data if k in SECTIONS)}
        write_data(data)
        log(f"section {s} done in {time.time() - t0:.0f} s -> {DATA_JS.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
