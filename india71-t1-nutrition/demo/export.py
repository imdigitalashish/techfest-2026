def log(msg: str) -> None:
    print(f"[export {datetime.now().strftime('%H:%M:%S')}] {msg}", flush=True)


def memory_level() -> int | None:
    try:
        return int(subprocess.check_output(["sysctl", "-n", "kern.memorystatus_level"], text=True).strip())
    except Exception:
        return None


def memory_guard(start_at: int = 30) -> None:
    """Start heavy work only when the macOS memory level is >= start_at; otherwise wait (no-op off macOS)."""
    level = memory_level()
    while level is not None and level < start_at:
        log(f"memory level {level} < {start_at}: waiting 30 s")
        time.sleep(30)
        level = memory_level()


def r4(x):
    return None if x is None or (isinstance(x, float) and np.isnan(x)) else round(float(x), 4)


