"""Summarise eval/results/<tag>_*.jsonl into eval/results/<tag>_summary.md.

Usage: python -m eval.summarize --tag v1
"""
from __future__ import annotations

import argparse
import json
import statistics
from collections import defaultdict
from pathlib import Path

OUT = Path(__file__).resolve().parent / "results"
ORDER = ["fedavg_ab_homo", "fedavg_ab_het", "anchor_naive", "anchor_full"]
LABEL = {
    "fedavg_ab_homo": "FedAvg on A,B — rank 8 everywhere (starter baseline)",
    "fedavg_ab_het": "FedAvg on A,B — device ranks, zero-padded (HetLoRA-style)",
    "anchor_naive": "Frozen shared A, nested ranks, n_k weights (FFA-LoRA-style)",
    "anchor_full": "AnchorLoRA: + FedNova norm, macro weights, clip, memory, partial work",
}
COLS = [("final_macro_loss", "macro ↓"), ("final_worst_loss", "worst ↓"), ("weak_gain", "weak-device gain ↑"),
        ("final_min_rel_gain", "min rel. gain ↑"), ("dominance_c0", "c0 share"), ("aggregation_error", "agg. error"),
        ("max_spike", "max spike ↓")]


def fmt(vals: list[float]) -> str:
    if len(vals) == 1:
        return f"{vals[0]:.4f}"
    return f"{statistics.mean(vals):.4f} ± {statistics.stdev(vals):.4f}"


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--tag", default="v1")
    args = ap.parse_args()
    lines = [f"# Results `{args.tag}` (auto-generated by `python -m eval.summarize --tag {args.tag}`)", ""]
    for path in sorted(OUT.glob(f"{args.tag}_*.jsonl")):
        runs = [json.loads(l) for l in path.read_text().splitlines() if l.strip()]
        if not runs:
            continue
        by = defaultdict(list)
        for r in runs:
            by[r["strategy"]].append(r)
        r0 = runs[0]
        cfg = r0["config"]
        lines += [f"## Scenario `{r0['scenario']}` — `{path.name}`", "",
                  f"Model {cfg['model_id']}, LoRA on {', '.join(cfg['targets'])} (r_max {cfg['r_max']}, α {cfg['alpha']}), "
                  f"{cfg['rounds']} rounds, batch {cfg['batch_size']}×{cfg['seq_len']}, lr {cfg['lr']}; "
                  f"base-model macro loss **{r0['base_macro_loss']:.4f}**; env {r0.get('env', {})}.", "",
                  "| Strategy | seeds | " + " | ".join(c[1] for c in COLS) + " | upload MB (c0…c4) | wall s |",
                  "|---" * (len(COLS) + 4) + "|"]
        for s in ORDER + [k for k in by if k not in ORDER]:
            if s not in by:
                continue
            rs = by[s]
            up = {c: statistics.mean(r["upload_mb"].get(c, 0.0) for r in rs) for c in rs[0]["upload_mb"]}
            lines.append(f"| {LABEL.get(s, s)} | {','.join(str(r['seed']) for r in rs)} | "
                         + " | ".join(fmt([r[c[0]] for r in rs]) for c in COLS)
                         + f" | {' / '.join(f'{v:.1f}' for v in up.values())} | {statistics.mean(r['wall_s'] for r in rs):.0f} |")
        lines += ["", "Per-domain final loss (seed mean):", "",
                  "| Strategy | " + " | ".join(r0["final_per_domain_loss"]) + " |",
                  "|---" * (len(r0["final_per_domain_loss"]) + 1) + "|"]
        for s in ORDER + [k for k in by if k not in ORDER]:
            if s not in by:
                continue
            doms = by[s][0]["final_per_domain_loss"]
            lines.append(f"| {s} | " + " | ".join(
                f"{statistics.mean(r['final_per_domain_loss'][d] for r in by[s]):.4f}" for d in doms) + " |")
        lines.append("")
    (OUT / f"{args.tag}_summary.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
