#!/usr/bin/env python3
"""Check that every quoted number in a deliverable matches a committed result.

Usage: python scripts/check_numbers.py deliverables/round1-abstract.md --tag v2

Every token with >= 2 decimals, or followed by '%', must equal (at the precision shown, sign optional) some value
in eval/results/<tag>_canonical.json or <tag>_dropout_canonical.json (generated by `python -m eval.summarize`
and `python -m eval.dropout_analysis`). Percentages match 100 × a canonical fraction. Text after a line
starting with '---' (team notes) is ignored. Exit code 1 if anything is unmatched.
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TOKEN = re.compile(r"(?<![\w.])([+\-−±]?)(\d+(?:\.\d+)?)(\s*%)?(?![\w.])")


def load(tag: str) -> dict:
    canon = {}
    for name in (f"{tag}_canonical.json", f"{tag}_dropout_canonical.json"):
        p = ROOT / "eval" / "results" / name
        if p.exists():
            canon.update({k: v for k, v in json.loads(p.read_text()).items() if isinstance(v, (int, float))})
    canon["const.upload_ratio_theory"] = 1920 / 768  # (d_in + d_out) / d_out for q_proj/v_proj pairs
    canon["const.ci_level"] = 0.95
    return canon


def match(val: float, decimals: int, pct: bool, canon: dict) -> list[str]:
    tol = 0.5 * 10 ** (-decimals) + 1e-12
    hits = []
    for k, v in canon.items():
        x = 100 * v if pct else v
        if abs(abs(x) - val) <= tol:
            hits.append(k)
    return hits


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("files", nargs="+")
    ap.add_argument("--tag", default="v2")
    args = ap.parse_args()
    canon = load(args.tag)
    bad = 0
    for f in args.files:
        text = Path(f).read_text().split("\n---\n")[0]
        print(f"== {f}")
        for m in TOKEN.finditer(text):
            sign, num, pct = m.group(1), m.group(2), bool(m.group(3))
            decimals = len(num.split(".")[1]) if "." in num else 0
            if decimals < 2 and not pct:
                continue
            hits = match(float(num), decimals, pct, canon)
            shown = f"{sign}{num}{'%' if pct else ''}"
            if hits:
                print(f"  OK   {shown:>10}  ← {hits[0]}" + (f" (+{len(hits) - 1} more)" if len(hits) > 1 else ""))
            else:
                bad += 1
                ctx = text[max(0, m.start() - 50): m.end() + 30].replace("\n", " ")
                print(f"  MISS {shown:>10}  …{ctx}…")
    print(f"{'FAIL' if bad else 'PASS'}: {bad} unmatched number(s)")
    sys.exit(1 if bad else 0)


if __name__ == "__main__":
    main()
