"""Parse the state-wise T&D-loss annex of Lok Sabha Unstarred Question 842 (answered 04.12.2025; CEA General
Review data for FY 2023-24) into cited records.

Reproduce (from ev-c2-green-auto-lca/):
    python3 data/fetch/parse_state_td_losses.py > data/factors/energy_state_td.yaml
Needs: .data/raw/electricity/ls_au842.pdf (see fetch_sources.sh) and pdftotext.
"""
import re
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
PDF = ROOT / ".data/raw/electricity/ls_au842.pdf"


def slug(name: str) -> str:
    return re.sub(r"[^a-z0-9]+", "_", name.lower()).strip("_")


def main() -> None:
    text = subprocess.run(["pdftotext", "-layout", str(PDF), "-"], capture_output=True, text=True, check=True).stdout
    annex = text[text.index("State-wise T&D Losses for FY 2023-24"):]
    rows = re.findall(r"^\s{2,}([A-Za-z][A-Za-z&.,' ]+?)\s{3,}(\d{1,2}\.\d{2})\s*$", annex, flags=re.M)
    print("# State-wise T&D losses FY 2023-24 — generated by data/fetch/parse_state_td_losses.py; do not edit by hand.")
    print("# geography uses IN-<state slug>; ISO 3166-2 mapping is a TODO.")
    for name, pct in rows:
        name = name.strip()
        if name == "All India":
            continue
        s = slug(name)
        print(f"""- id: energy.electricity.in_{s}.td_loss_share.fy2023_24
  layer: energy
  name: "T&D losses, {name} (share of energy available)"
  value: {round(float(pct) / 100, 4)}
  unit: fraction
  quantity: share
  gas_basis: n/a
  boundary: "State T&D losses incl. commercial losses (theft, unbilled)."
  geography: IN-{s}
  reference_year: "2023-24"
  technology: state transmission + distribution network
  source_id: loksabha-usq842-2025
  locator: "Annexure, State-wise T&D Losses for FY 2023-24"
  quote: "{name} {pct}"
  accessed: 2026-10-04
  pedigree: {{reliability: 1, completeness: 1, temporal: 2, geographical: 1, technological: 2}}
  status: verified""")


if __name__ == "__main__":
    main()
