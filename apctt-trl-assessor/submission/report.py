"""Summarise a dry run into markdown (stdout): validity, accuracy on gold docs, time, memory, deps, licences.
Usage (from apctt-trl-assessor/): python submission/report.py --dist DIST --dryrun DRYRUN --install-s N
"""
from __future__ import annotations

import argparse
import hashlib
import json
import re
import subprocess
from pathlib import Path

import numpy as np

from components.skeleton import emit

K = 9


def qwk(y, p):
    O = np.zeros((K, K))
    for a, b in zip(y, p):
        O[a - 1, b - 1] += 1
    W = (np.subtract.outer(np.arange(K), np.arange(K)) ** 2) / (K - 1) ** 2
    E = np.outer(O.sum(1), O.sum(0)) / O.sum()
    return float(1 - (W * O).sum() / (W * E).sum())


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--dist"); ap.add_argument("--dryrun"); ap.add_argument("--install-s", type=float, default=-1)
    a = ap.parse_args()
    dist, dr = Path(a.dist), Path(a.dryrun)
    schema = emit.load_schema(dist / "trl_assessor" / "resources" / "contracts.schema.json")
    inputs = sorted(p for p in (dr / "in").iterdir() if p.is_file())
    outs = {p.name.replace(".assessment.json", ""): json.loads(p.read_text()) for p in (dr / "out").glob("*.assessment.json")}
    invalid = {k: emit.check_assessment(v, schema) for k, v in outs.items()}
    invalid = {k: v for k, v in invalid.items() if v}
    gold = json.loads((dr / "gold.json").read_text())
    y = np.array([gold[k] for k in gold if k in outs]); p = np.array([outs[k]["decision"]["trl"] for k in gold if k in outs])
    t = (dr / "time.txt").read_text()
    real = float(re.search(r"([\d.]+) real", t).group(1)); cpu = float(re.search(r"([\d.]+) user", t).group(1)) + float(re.search(r"([\d.]+) sys", t).group(1)); rss = int(re.search(r"(\d+)\s+maximum resident set size", t).group(1))
    last = [l for l in (dr / "run.log").read_text().splitlines() if "docs/s" in l][-1]
    pkgs = json.loads(subprocess.run([str(dr / "venv/bin/python"), "-c",
        "import importlib.metadata as m, json; print(json.dumps(sorted([(d.metadata['Name'], d.version, "
        "(d.metadata.get('License-Expression') or d.metadata.get('License') or '').split(chr(10))[0][:60], "
        "[c.split('::')[-1].strip() for c in (d.metadata.get_all('Classifier') or []) if c.startswith('License')]) "
        "for d in m.distributions()])))"], capture_output=True, text=True).stdout)
    z = dist.with_suffix(".zip")
    size = sum(f.stat().st_size for f in dist.rglob("*") if f.is_file() and "__pycache__" not in f.parts)
    print(f"""# Submission dry run — {dist.name}

_Generated by `submission/dry_run.sh` (clean venv, pinned deps, `--offline` network guard, `/usr/bin/time -l`). All numbers below come from this run._

| Check | Result |
|---|---|
| Inputs | {len(inputs)} files ({len(gold)} held-out TechPort docs + {len(inputs) - len(gold)} synthetic edge cases: empty, non-English, 1 MB text, HTML, corrupt PDF, real PDF if `cupsfilter` exists) |
| Outputs written | {len(outs)} / {len(inputs)} |
| Schema-valid (internal `Assessment` contract) | {len(outs) - len(invalid)} / {len(outs)} |
| Offline | run with `--offline` (socket connect/getaddrinfo raise) — {'completed without network' if len(outs) == len(inputs) else 'INCOMPLETE'} |
| Wall time, whole batch incl. Python start-up | {real:.2f} s (CPU user+sys {cpu:.2f} s — wall ≫ CPU means the shared machine was I/O-loaded) |
| Throughput (runner's own clock) | {last.strip()} |
| Peak RSS | {rss / 1e6:.0f} MB |
| Dependency install (uv, from cache or network) | {a.install_s:.0f} s |
| Package size | {size / 1e3:.0f} kB unpacked; zip {z.stat().st_size / 1e3:.0f} kB; sha256 `{hashlib.sha256(z.read_bytes()).hexdigest()[:16]}…` |
| Sanity accuracy on the {len(y)} held-out docs (v0 model, median decoding) | exact {np.mean(y == p):.3f} · within-1 {np.mean(abs(y - p) <= 1):.3f} · MAE {np.mean(abs(y - p)):.3f} · QWK {qwk(y, p):.3f} |

## Installed packages in the clean venv (name · version · licence metadata as declared by the package)
""")
    for name, ver, lic, cls in pkgs:
        print(f"- {name} {ver} — {lic or '(no License field)'}{' · ' + '; '.join(cls) if cls else ''}")
    if invalid:
        print("\n## Schema violations\n")
        for k, v in list(invalid.items())[:10]:
            print(f"- {k}: {v[:3]}")
    print("\nLicence entries are the packages' own metadata, not a legal review. The official output schema (10 Oct) replaces the internal contract in C7.")


if __name__ == "__main__":
    main()
