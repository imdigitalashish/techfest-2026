"""Render the README results block from results/*.json (no hand-copied numbers).

    python -m t3det.report            # prints markdown
    python -m t3det.report --write    # replaces the block between the RESULTS markers in README.md
"""
from __future__ import annotations

import json
import sys

from .paths import COMP, RESULTS

BEGIN, END = "<!-- RESULTS:BEGIN (generated by python -m t3det.report) -->", "<!-- RESULTS:END -->"


def _j(name: str) -> dict | None:
    p = RESULTS / name
    return json.loads(p.read_text()) if p.exists() else None


def render() -> str:
    m, z = _j("metrics.json"), _j("metrics_zeroshot.json")
    trained = m is not None and "ZERO-SHOT" not in m.get("baseline_kind", "")
    out = []
    if trained:
        tr = m["training"]
        o = m["other_splits"]
        et = tr.get("epoch_time_s") or {}
        out += [f"**Trained baseline** `{m['model_id']}` on **{m['device'].upper()}** "
                f"({tr['epochs_completed']} epochs, median {et.get('median')} s/epoch, total wall-clock "
                f"{tr['total_wall_clock_s']} s; {tr.get('start_ist')} → {tr.get('end_ist')}).", "",
                "| Split | Images | mAP50 | mAP50-95 | P | R |", "|---|---|---|---|---|---|",
                f"| **TUD-GV test (held out, evaluated once)** | {m['n_test_images']} | **{m['mAP50']}** | **{m['mAP50_95']}** "
                f"| {m['precision']} | {m['recall']} |"]
        for s, label in (("val", "TUD-GV val (used for best.pt selection)"), ("groningen", "Groningen cross-site (never trained on)")):
            if s in o:
                out.append(f"| {label} | {o[s]['n_images']} | {o[s]['mAP50']} | {o[s]['mAP50_95']} | {o[s]['precision']} | {o[s]['recall']} |")
        lat = m["latency_ms_mps"]
        out += ["", f"Latency, end-to-end `predict()` at batch 1 on {lat['device']}: median {lat['median']} ms/img, p90 {lat['p90']} "
                f"(n={lat['n']}; shared machine, niced, GPU shared with another app: an upper bound). P/R: ultralytics' values at its max-F1 confidence."]
        fz = m.get("frozen_matcher_test")
        if fz:
            out += ["", f"Same metric code as the zero-shot reference (frozen matcher, test): trained mAP50 "
                    f"**{fz['trained']['mAP50']}** (boot SE {fz['trained']['boot_se']}, R@0.25 {fz['trained']['recall@0.25']}) "
                    f"vs zero-shot {fz['zero_shot']['mAP50']} (R@0.25 {fz['zero_shot']['recall@0.25']})."]
    out += ["", "| C6 flux (**SYNTHETIC**, ByteTrack + line) | Detector | GT crossings | Counted | Count error |", "|---|---|---|---|---|"]
    for name, det in (("flux_synthetic.json", "trained" if trained else "zero-shot"),
                      ("flux_synthetic_seq01.json", "trained"), ("flux_synthetic_zeroshot.json", "zero-shot")):
        f = _j(name)
        if f:
            out.append(f"| {f['sequence']} ({f['frames']} frames) `results/{name}` | {det} | {f['gt_crossings']} | "
                       f"{f['items_crossed']} | {f['count_error_pct']}% |")
    if z:
        out += ["", f"**Zero-shot reference** (`results/metrics_zeroshot.json`, COCO-pretrained YOLO11n, not trained on "
                f"TUD-GV, frozen matcher): test mAP50 {z['mAP50']}, mAP50-95 {z['mAP50_95']}, P {z['precision']} / "
                f"R {z['recall']} at score ≥ 0.25."]
    return "\n".join(out)


def main() -> None:
    md = render()
    if "--write" in sys.argv:
        p = COMP / "README.md"
        t = p.read_text()
        a, b = t.index(BEGIN) + len(BEGIN), t.index(END)
        p.write_text(t[:a] + "\n" + md + "\n" + t[b:])
    print(md)


if __name__ == "__main__":
    main()
