"""Render the Round-1 deliverables from deliverables/src/ templates and committed results.

Placeholders:
  {{r:alias}}       -> a number from a committed run (eval/doc_numbers.py ALIASES)
  {{f:ID|text}}     -> cited text; check_docs.py verifies every number in `text` appears in research/fact-check.md row ID
Usage (from anywhere): python3 innovatex-t3-coastal-plastic/eval/render_docs.py
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from doc_numbers import ROOT, value  # noqa: E402

SRC = ROOT / "deliverables" / "src"
OUT = ROOT / "deliverables"
PH = re.compile(r"\{\{(r|f):([^}|]+)(?:\|([^}]*))?\}\}")
TEMPLATES = sorted(SRC.glob("*.md"))
NOTICE = "GENERATED by eval/render_docs.py from deliverables/src/{name} and committed results; edit the source, not this file."


def render_text(text: str) -> str:
    def sub(m: re.Match) -> str:
        kind, key, txt = m.group(1), m.group(2).strip(), m.group(3)
        if kind == "r":
            return value(key)
        if txt is None:
            raise ValueError(f"fact placeholder {key} needs text: {{{{f:{key}|text}}}}")
        return txt
    return PH.sub(sub, text)


def render_file(src: Path) -> str:
    body = render_text(src.read_text())
    note = NOTICE.format(name=src.name)
    if body.startswith("---\n"):  # Marp front matter: a YAML comment keeps the notice out of the slides
        return body.replace("---\n", f"---\n# {note}\n", 1)
    return f"<!-- {note} -->\n" + body


def render_all() -> dict[Path, str]:
    return {OUT / s.name: render_file(s) for s in TEMPLATES}


def main() -> None:
    for path, text in render_all().items():
        path.write_text(text)
        print("rendered", path.relative_to(ROOT))


if __name__ == "__main__":
    main()
