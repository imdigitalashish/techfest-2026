"""Deterministic paired-bootstrap verdict for a confirmatory test (review sol #7).

Paired by seed; seeds sorted; fresh RandomState(0) per metric; 20,000 resamples. Reports the
two-sided 95% CI, the one-sided 95% upper bound and the bootstrap tail fraction P(boot mean >= 0).
The tail fraction is a resampling statistic, NOT a calibrated null-hypothesis p-value.
Usage: .venv/bin/python eval/h1_verdict.py --exp E6_confirm_sync --label IA_sched_only
       .venv/bin/python eval/h1_verdict.py --exp E10_replication_test --label IA_sched_only --name H2
"""
import argparse, os
import numpy as np
import pandas as pd

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--exp", required=True); ap.add_argument("--label", default="IA_sched_only")
    ap.add_argument("--base", default="TWAP"); ap.add_argument("--name", default="H1"); ap.add_argument("--n", type=int, default=20000)
    a = ap.parse_args()
    df = pd.read_csv(os.path.join(ROOT, "eval", "results", f"{a.exp}.csv"))
    L = [f"# {a.exp}: {a.name} verdict ({a.label} vs {a.base}); generated by eval/h1_verdict.py", "",
         f"n = {df.seed.nunique()} seeds; paired by seed, seeds sorted; fresh RandomState(0) per metric; {a.n:,} resamples. "
         "The tail fraction P(boot mean ≥ 0) is a resampling statistic, not a calibrated p-value.", "",
         "| metric | mean Δ (bps) | 95% CI | one-sided 95% upper bound | P(boot mean ≥ 0) |", "|---|---|---|---|---|"]
    verdict = None
    for m in ["is_bps", "own_impact_bps", "instant_bps", "drift_bps"]:
        P = df.pivot(index="seed", columns="label", values=m).sort_index()
        d = (P[a.label] - P[a.base]).values
        bm = np.random.RandomState(0).choice(d, size=(a.n, len(d))).mean(1)
        up = np.percentile(bm, 95)
        L.append(f"| {m} | {d.mean():+.4f} | [{np.percentile(bm, 2.5):+.4f}, {np.percentile(bm, 97.5):+.4f}] | {up:+.4f} | {np.mean(bm >= 0):.4f} |")
        if m == "is_bps":
            verdict = "CONFIRMED" if up < 0 else "NOT CONFIRMED"
            win = np.mean(d < 0)
    L += ["", f"**{a.name} {verdict}** (one-sided α = 0.05: the upper bound must be < 0). Win rate {win:.0%}."]
    out = os.path.join(ROOT, "eval", "results", f"{a.exp}_{a.name}_verdict.md")
    open(out, "w").write("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
