"""Export the committed eval rows to demo/web/replay.js (window.REPLAY = {...}) for the offline REPLAY view, or --check it.

Numbers are copied from eval/results/<run>.rows.jsonl, or aggregated by eval/render_docs.py, the code that renders
eval/RESULTS.md (tables, verdicts, mechanism). Display strings use render_docs' own formats. Needle/question text is
regenerated by the committed workload generator eval/kvbench_torch.make_sample (same seed, style and length; tokenizer
+ .data/haystack.txt, no model) and every regenerated needle is checked against the rows (value, token position, T).

Usage (from perceptron-p02-kv-cache/):
  python3 demo/export_replay.py          write demo/web/replay.js
  python3 demo/export_replay.py --check  exit 1 unless replay.js equals a fresh export and its tables and verdicts
                                         appear verbatim in eval/RESULTS.md
"""
from __future__ import annotations

import argparse
import json
import math
import random
import sys
from collections import defaultdict

import common  # noqa: F401  (puts eval/ on sys.path)
import render_docs as rd

OUT = common.WEB / "replay.js"
PREFIX, SUFFIX = "window.REPLAY=", ";\n"
PER_TOK, BLOCK, N_SINK, WQ_BYTES = 32768, 64, 4, 262144
LABELS = {"T1": ("T1 · literal needles", "pre-registered primary test, seed 0"),
          "T2": ("T2 · paraphrased needles", "replication on fresh contexts, seed 1"),
          "T3": ("T3 · alias needles", "question names the key with synonyms, seed 2"),
          "S4": ("S4 · RoD + 64-token halo", "T1 contexts; recalled blocks re-prefilled with 64 tokens of left context")}
NAMES = {k: v.replace("**", "") for k, v in rd.NAMES.items()}
GROUPS = [["Reference", ["full"]],
          ["Ours (compress before the question; recall when it arrives)", ["rod", "rodlex"]],
          ["Query-agnostic eviction baselines", ["streaming", "kvp_streaming", "h2o", "kvp_observed", "snapkv", "kvp_snapkv",
                                                 "knorm", "kvp_knorm", "kvp_expected", "kvp_tova", "random"]],
          ["Quantise every token (no eviction)", ["int8", "int4", "int2"]],
          ["Oracle: sees the question before compressing", ["snapkv_qa"]]]


def pk(f):
    return str(round(f * 100))


def rod_layout(T, f, lexical, sketch_bytes, stored):
    """kvbench_torch.rod_build's budget arithmetic (frozen config: layer 5, 4-bit, softmax_lift), checked against the row."""
    B = max(N_SINK + 64 + 1, round(f * T))
    extra = (0 if lexical else 8 * (64 * 4 // 8 + 4) * T + WQ_BYTES) + 4 * T
    B_kv = max(N_SINK + 2, B - math.ceil(extra / PER_TOK))
    B_res = max(N_SINK + 1, B_kv // 2)
    assert stored == B_res * PER_TOK + sketch_bytes + 4 * T, (T, f, lexical, stored)
    ev1 = T - (B_res - N_SINK)
    return {"B": B, "B_res": B_res, "ev1": ev1, "m": (B_kv - B_res) // BLOCK, "sketch_bytes": sketch_bytes,
            "nblk": -(-(ev1 - N_SINK) // BLOCK)}


def regenerate(meta, tok, paras, cache):
    key = (meta["seed"], meta["style"], meta["ctx_target"], meta["needles"], meta["n_contexts"])
    if key not in cache:
        import kvbench_torch as kb
        rng, ctxs = random.Random(meta["seed"]), []
        tn, tq = kb.STYLES[meta["style"]]
        for si in range(meta["n_contexts"]):
            ctx_ids, qs = kb.make_sample(tok, paras, meta["ctx_target"], meta["needles"], rng, meta["style"])
            T = len(ctx_ids)
            snips = [tok.decode(ctx_ids[s:s + BLOCK], skip_special_tokens=True).replace("\n", " ").strip()[:40]
                     for s in range(N_SINK, T, BLOCK)]
            ctxs.append({"sample": si, "T": T, "snips": snips, "needles": [
                {"q": qi, "key": nd["key"], "qkey": nd.get("qkey", nd["key"]), "value": nd["value"],
                 "needle": tn.format(k=nd["key"], v=nd["value"]), "question": tq.format(k=nd.get("qkey", nd["key"])),
                 "pos": nd["pos"], "depth_tok": nd["depth_tok"]} for qi, (_, nd) in enumerate(qs)]})
        cache[key] = ctxs
    return cache[key]


def run_export(k, D, V, tok, paras, cache):
    rows, meta = D["rows"], D["meta"]
    ctxs = regenerate(meta, tok, paras, cache)
    by_ctx = {c["sample"]: c for c in ctxs}
    for r in rows:  # the regenerated workload must be the one that was evaluated
        c = by_ctx[r["sample"]]
        nd = c["needles"][r["q"]]
        assert (c["T"], nd["value"], nd["pos"], nd["depth_tok"]) == (r["T"], r["value"], r["pos"], r["depth_tok"]), (k, r["sample"], r["q"])
    out_rows, layout = defaultdict(list), defaultdict(dict)
    for r in sorted(rows, key=lambda r: (r["method"], r["frac"], r["sample"], r["q"])):
        key = f"{r['method']}|{pk(r['frac'])}"
        out_rows[key].append([r["sample"], r["q"], r["answer"], int(r["correct"]), r["stored_bytes"], r["answer_time_bytes"],
                              r.get("recalled_blocks"), r.get("needle_block_hit"), r.get("needle_evicted")])
        if r["method"] in ("rod", "rodlex"):
            lay = rod_layout(r["T"], r["frac"], r["method"] == "rodlex", r.get("sketch_bytes", 0), r["stored_bytes"])
            if r.get("recalled_blocks") is not None:
                assert len(r["recalled_blocks"]) == min(lay["m"], lay["nblk"]), (k, key, r["sample"], r["q"])
            layout[key][str(r["sample"])] = lay
        elif r["method"] in ("streaming", "kvp_streaming"):
            layout[key][str(r["sample"])] = {"B": r["B"]}
    vals = defaultdict(set)
    for r in rows:
        vals[r["sample"]].add(r["value"])
    rod = {(r["sample"], r["q"], r["frac"]): r for r in rows if r["method"] == "rod"}
    confusion = []
    for (s, q, f), r in sorted(rod.items()):
        lo = rod.get((s, q, 0.1))
        if f == 0.25 and lo and lo["correct"] and not r["correct"] and r.get("needle_block_hit"):
            other = [v for v in vals[s] - {r["value"]} if v in r["answer"].replace(",", "")]
            if other:
                confusion.append({"sample": s, "q": q, "answer_10": lo["answer"], "answer_25": r["answer"], "other_value": other[0]})
    tab = V["S4tab"] if k == "S4" else V[k]
    table = [{"m": t["m"], "f": t["f"], "n": t["n"], "acc": round(t["acc"], 4), "lo": round(t["lo"], 4), "hi": round(t["hi"], 4),
              "stored": round(t["stored"], 3), "answer": round(t["answer"], 3), "full": round(t["full"], 3),
              "hit": None if t["hit"] is None else round(t["hit"], 4),
              "md": {"acc": f"{t['acc']:.3f}", "ci": f"{t['lo']:.2f}–{t['hi']:.2f}", "stored": f"{t['stored']:.1f}",
                     "x": f"{t['x']:.1f}×", "answer": f"{t['answer']:.1f}", "s": f"{t['s']:.2f}",
                     "hit": "" if t["hit"] is None else f"{t['hit']:.2f}"}} for t in tab]
    mech = {m: {pk(f): {kk: round(vv, 4) if isinstance(vv, float) else vv for kk, vv in d.items()} for f, d in rd.mech(rows, m).items()}
            for m in ("rod", "rodlex")}
    label, sub = LABELS.get(k, (meta["name"], ""))
    return {"key": k, "name": meta["name"], "label": label, "sub": sub, "style": meta["style"], "seed": meta["seed"],
            "halo": meta.get("halo", 0), "command": meta["command"], "cpu": meta["cpu"], "threads": meta["threads"],
            "wall_s": meta["wall_s"], "n_contexts": meta["n_contexts"], "needles": meta["needles"],
            "mean_T": round(V["meanT"][k], 1), "methods": sorted({r["method"] for r in rows}, key=lambda m: list(NAMES).index(m)),
            "fracs": sorted({pk(r["frac"]) for r in rows}, key=int), "table": table, "mech": mech, "confusion": confusion,
            "contexts": ctxs, "rows": dict(out_rows), "layout": dict(layout)}


def build():
    D = {k: rd.load(k) for k in rd.SPLITS}
    V = rd.compute()
    tok = common.load_tokenizer()
    paras = (common.DATA / "haystack.txt").read_text(encoding="utf-8").split("\n")
    cache, runs = {}, []
    for k in rd.SPLITS:
        if D[k] is not None and (V.get(k) or V.get("S4tab") and k == "S4"):
            runs.append(run_export(k, D[k], V, tok, paras, cache))
    posthoc = None
    ph = common.ROOT / "eval" / "results" / "posthoc_T1.json"
    if ph.exists():  # exploratory (PREREG amendment 3); strings formatted exactly as render_docs renders them
        P = json.loads(ph.read_text())
        posthoc = {"label": P["label"], "command": P["command"], "rows": []}
        for f, x in P["summary"].items():
            c = {"b": pk(float(f)), "n": x["n"], "m": f"{x['m_mean']:.1f}", "rod": "n/a" if x["rod_T1_acc"] is None else f"{x['rod_T1_acc']:.3f}",
                 "e2": f"{x['e2_exactkv_acc']:.3f}", "e3": f"{x['e3_oracleblk_acc']:.3f}", "e23": f"{x['e23_both_acc']:.3f}",
                 "e5": "n/a" if x.get("e5_top2_acc") is None else format(x["e5_top2_acc"], ".3f")}
            c["md"] = (f"| {float(f):.2f} | {x['n']} | {c['m']} | {x['streamed_equal']}/{x['n']} | {x['t1_recorded_equal']}/{x['n']} | "
                       f"{c['rod']} | {c['e2']} | {c['e3']} | {c['e23']} | {c['e5']} |")
            posthoc["rows"].append(c)
    e6 = rd.e6_delta() if hasattr(rd, "e6_delta") else None
    if e6 is not None:  # exploratory (PREREG amendment 5): T2 re-answered with 32-token answers, strict first-number scoring
        rows6 = [json.loads(l) for l in (common.ROOT / "eval" / "results" / "e6_maxnew32_T2.rows.jsonl").read_text().splitlines() if l.strip()]
        k = lambda m, f: sum(bool(r["strict"]) for r in rows6 if r["method"] == m and r["frac"] == f)
        n = lambda m, f: sum(1 for r in rows6 if r["method"] == m and r["frac"] == f)
        e6 = {"full_k": k("full", 1.0), "rod_k": k("rod", 0.1), "n": n("full", 1.0), "n_rod": n("rod", 0.1), "n_ctx": e6["n"],
              "d_s": f"{e6['d']:+.2f}", "lo_s": f"{e6['lo']:+.2f}", "hi_s": f"{e6['hi']:+.2f}",
              "full": round(e6["full"], 4), "rod": round(e6["rod"], 4), "max_new": 32, "scoring": "strict first-number"}
        assert e6["n"] == e6["n_rod"] and abs(e6["full_k"] / e6["n"] - e6["full"]) < 1e-4 and abs(e6["rod_k"] / e6["n"] - e6["rod"]) < 1e-4, e6
    return {"generated_by": "demo/export_replay.py from eval/results/*.rows.jsonl via eval/render_docs.py",
            "e6": e6,
            "posthoc_T1": posthoc,
            "model": "Llama-3.2-1B-Instruct (mlx-community 4-bit @ 08231374, dequantised; fp32 compute on CPU, fp16 KV)",
            "kv_bytes_per_token": PER_TOK, "block": BLOCK, "n_sink": N_SINK, "names": NAMES, "groups": GROUPS,
            "headline": rd.headline(V), "verdicts": rd.verdicts(V).split("\n"), "runs": runs}, V


def first_diff(a, b, path="$"):
    if type(a) is not type(b):
        return f"{path}: type {type(a).__name__} != {type(b).__name__}"
    if isinstance(a, dict):
        for k in sorted(set(a) | set(b)):
            if k not in a or k not in b:
                return f"{path}.{k}: missing on one side"
            d = first_diff(a[k], b[k], f"{path}.{k}")
            if d:
                return d
    elif isinstance(a, list):
        if len(a) != len(b):
            return f"{path}: length {len(a)} != {len(b)}"
        for i, (x, y) in enumerate(zip(a, b)):
            d = first_diff(x, y, f"{path}[{i}]")
            if d:
                return d
    elif a != b:
        return f"{path}: {a!r} != {b!r}"
    return None


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    data, V = build()
    fresh = json.loads(json.dumps(data, ensure_ascii=False))
    if not a.check:
        common.WEB.mkdir(parents=True, exist_ok=True)
        OUT.write_text(PREFIX + json.dumps(fresh, ensure_ascii=False, separators=(",", ":")) + SUFFIX)
        print(f"wrote {OUT.relative_to(common.ROOT)} ({OUT.stat().st_size / 1024:.0f} KiB): runs "
              + ", ".join(f"{r['key']} ({len(r['contexts'])} contexts, {sum(len(v) for v in r['rows'].values())} rows)" for r in fresh["runs"]))
        return 0
    fails = []
    txt = OUT.read_text() if OUT.exists() else ""
    committed = json.loads(txt[len(PREFIX):-len(SUFFIX)]) if txt.startswith(PREFIX) and txt.endswith(SUFFIX) else None
    d = "replay.js missing or malformed" if committed is None else first_diff(fresh, committed)
    if d:
        fails.append(f"demo/web/replay.js is stale vs committed rows ({d}); run: python3 demo/export_replay.py")
    res = (common.ROOT / "eval" / "RESULTS.md").read_text().splitlines()
    rset = set(res)
    for line in fresh["verdicts"]:
        if line not in rset:
            fails.append(f"verdict not in eval/RESULTS.md: {line[:90]}")
    n_lines = 0
    for r in fresh["runs"]:
        for line in rd.md_table(V["S4tab"] if r["key"] == "S4" else V[r["key"]]).splitlines()[2:]:
            n_lines += 1
            if line not in rset:
                fails.append(f"{r['key']} table row not in eval/RESULTS.md: {line[:90]}")
        for t in r["table"]:  # the strings the page shows are render_docs' strings
            md = t["md"]
            row = f"| {rd.NAMES.get(t['m'], t['m'])} | {t['f']:.2f} | {md['acc']} | {md['ci']} | {md['stored']} | {md['x']} | {md['answer']} | {md['s']} | {md['hit']} |"
            if row not in rset:
                fails.append(f"{r['key']} on-screen strings differ from eval/RESULTS.md: {row[:90]}")
    e6 = fresh.get("e6")
    if e6:  # the E6 figures the page leads T2 with must be the ones render_docs renders
        frag = f"({e6['d_s']}, 95% CI {e6['lo_s']} to {e6['hi_s']}; exploratory)"
        if frag not in fresh["headline"]:
            fails.append(f"E6 paired delta {frag} not in render_docs' headline")
        e6line = next((v for v in fresh["verdicts"] if v.startswith("- **E6")), "")
        for m, kk in (("full@1.0", "full_k"), ("rod@0.1", "rod_k")):
            if f"{m} {e6[kk] / e6['n']:.3f}" not in e6line:
                fails.append(f"E6 count {m} {e6[kk]}/{e6['n']} disagrees with the E6 verdict line")
    for row in (fresh.get("posthoc_T1") or {}).get("rows", []):
        n_lines += 1
        if row["md"] not in rset:
            fails.append(f"post-hoc row not in eval/RESULTS.md: {row['md'][:90]}")
    for f in fails:
        print("FAIL", f)
    if not fails:
        print(f"export check OK: {len(fresh['runs'])} runs, {sum(len(r['contexts']) for r in fresh['runs'])} regenerated contexts match "
              f"their rows; {n_lines} table rows and {len(fresh['verdicts'])} verdict lines equal eval/RESULTS.md")
    return 1 if fails else 0


if __name__ == "__main__":
    sys.exit(main())
