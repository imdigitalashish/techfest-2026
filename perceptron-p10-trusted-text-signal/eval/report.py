"""Render eval/results/<tag>.json as Markdown: PYTHONPATH=. .venv/bin/python eval/report.py [tag]

Handles v1 results (oracle grid, guaranteed floor, burst attack, ACI stats, day-level CIs) and v0 results.
"""
import json
import sys
from pathlib import Path

TAG = sys.argv[1] if len(sys.argv) > 1 else "baseline_v1"
r = json.loads(Path(f"eval/results/{TAG}.json").read_text())
m = r["meta"]
f = lambda x: f"{x:.3f}"
pc = lambda x: f"{100 * x:.1f}%"


def ci(e):
    c = e.get("mean_day_coverage_ci90")
    return f"{pc(e['mean_day_coverage'])} [{pc(c[0])}, {pc(c[1])}]" if c else "—"


L = [f"# {TAG} — StockNet, time-ordered split (generated by `eval/report.py` from `{TAG}.json`)", "",
     f"Train {m['train'][0]}→{m['train'][1]} ({m['n_train']:,} ticker-days) · calibration {m['cal'][0]}→{m['cal'][1]} ({m['n_cal']:,}) · "
     f"test {m['test'][0]}→{m['test'][1]} ({m['n_test']:,}) · {m['tickers']} tickers · α = {m['alpha']} (target coverage 90%) · seed {m['seed']} · "
     f"text scorer: {m['text_scorer']} · y = next-day close-to-close log return in %, forecast issued after the 16:00 ET close "
     f"(widths in percentage points) · runtime {m['runtime_s']} s.", "",
     f"Reproduce: `bash eval/fetch_data.sh && PYTHONPATH=. nice -n 10 .venv/bin/python eval/prepare.py{' --scorer minilm' if 'MiniLM' in m['text_scorer'] else ''} && "
     f"PYTHONPATH=. nice -n 10 .venv/bin/python eval/run_baselines.py --tag {TAG}{' --scorer minilm' if 'MiniLM' in m['text_scorer'] else ''}`", "",
     "## Ablation × conformal method (clean test data)", "",
     "`cqr_aci` is our own ACI loop (Gibbs & Candès 2021) on CQR scores; split and CQR are MAPIE 1.5. "
     "Mean daily coverage has a 90% day-block bootstrap CI (date-cluster inference); pooled Kupiec/Christoffersen p-values ignore same-day correlation.", "",
     "| Model | Method | Coverage | Mean daily cov. [90% CI] | Mean width | Winkler | Kupiec p | Christoffersen p | Cov. high-vol | Cov. 5+ tweets |",
     "|---|---|---|---|---|---|---|---|---|---|"]
for name, a in r["ablation"].items():
    for meth in ["split", "cqr_mapie", "cqr_aci"]:
        e = a[meth]
        L.append(f"| {name} | {meth} | {pc(e['coverage'])} | {ci(e)} | {f(e['mean_width'])} | {f(e['winkler'])} | {e['kupiec_p']:.3g} | "
                 f"{e['christoffersen_p']:.3g} | {pc(e['cov[vol=high]'])} | {pc(e['cov[tweets=5+]'])} |")
L += ["", "| Model | Mean pinball (3 quantiles) | Spearman IC (median vs y) | IC on tweet days |", "|---|---|---|---|"]
for name, a in r["ablation"].items():
    L.append(f"| {name} | {a['pinball_mean']:.4f} | {a['ic_spearman']:.4f} | {a['ic_spearman_tweet_days']:.4f} |")

s = r["spike"]
base = r["ablation"]["fusion"]["cqr_sym"]
L += ["", "## Spike: certified CQR (fusion model), clean test data — price of robustness", "",
      "| Budget k | Coverage | Mean width | Width vs CQR (k = 0) | Cov. high-vol |", "|---|---|---|---|---|",
      f"| 0 (plain symmetric CQR) | {pc(base['coverage'])} | {f(base['mean_width'])} | — | {pc(base['cov[vol=high]'])} |"]
for k in (1, 2, 3, 5):
    e = s[f"clean_k{k}"]
    L.append(f"| {k} | {pc(e['coverage'])} | {f(e['mean_width'])} | +{100 * (e['mean_width'] / base['mean_width'] - 1):.1f}% | {pc(e['cov[vol=high]'])} |")

p, o = r["attack"]["pump"], r["attack"]["oracle"]
L += ["", "## Attacks (budget k = 3 injected documents per ticker-day; every test ticker-day attacked unless stated)", "",
      f"Pump: {p['k']} posts with the template's sentiment from the deployed scorer ({p['pump_sentiment']:.3f}) and the trust our scorer gives a "
      f"fresh, unverified, zero-follower account ({p['pump_trust']:.3f}). Median forecast shift {p['median_shift_mean']:+.4f} pp "
      f"(95th pct |shift| {p['median_shift_p95_abs']:.4f} pp).", "",
      "| Scenario | Method | Coverage | Mean width | Certified ⊇ clean-covered rows? |", "|---|---|---|---|---|",
      f"| none | CQR | {pc(base['coverage'])} | {f(base['mean_width'])} | — |",
      f"| pump | CQR | {pc(p['vanilla_cqr']['coverage'])} | {f(p['vanilla_cqr']['mean_width'])} | — |",
      f"| pump | certified CQR | {pc(p['certified']['coverage'])} | {f(p['certified']['mean_width'])} | {('yes' if p['floor_holds'] else 'NO') if 'floor_holds' in p else '— (not checked in v0)'} |"]
if not o.get("skipped"):
    if "grid_size" in o:
        L.append(f"| oracle: worst of {o['grid_size']} variants per row (knows y) | CQR | {pc(o['vanilla_cqr_oracle_coverage'])} | — | — |")
        for i, w in enumerate(o["worst3"], 1):
            L.append(f"| worst fixed variant #{i}: sents {w['sents']}, trusts {w['trusts']} | CQR / certified | "
                     f"{pc(w['vanilla_coverage'])} / {pc(w['certified_coverage'])} | {f(w['vanilla_width'])} / {f(w['certified_width'])} | "
                     f"{'yes' if w['floor_holds'] else 'NO'} |")
        L += ["", f"**Guaranteed floor:** for every attack within the budget, the certified interval covers every row that the clean CQR "
              f"interval covers, so certified coverage under attack ≥ {pc(o['certified_guaranteed_floor'])} (the clean CQR coverage). "
              f"The {o['grid_size']}-variant oracle against plain CQR is a search, not a worst-case bound."]
    else:
        L.append(f"| oracle (worst of {o['n_variants']} variants, knows y) | CQR / certified | {pc(o['vanilla_cqr_adversarial_coverage'])} / "
                 f"{pc(o['certified_adversarial_coverage'])} | — | — |")

c = s["cr_aci"]
st = s.get("aci_stats", {})
L += ["", "## CR-ACI (certified box + our ACI loop, γ = 0.01)", "",
      "| Run | Coverage | Mean daily cov. [90% CI] | Mean width | Cov. on attacked days | ACI α_t range | days α_t ≤ 0 / ≥ 1 |",
      "|---|---|---|---|---|---|---|"]
for nm, e in c.items():
    a = st.get(nm, {})
    att = pc(e["cov[burst=attacked]"]) if "cov[burst=attacked]" in e and "burst" in nm else "—"
    rng = f"[{a['alpha_min']:.3f}, {a['alpha_max']:.3f}]" if a else "—"
    bd = f"{a['alpha_le0_days']} / {a['alpha_ge1_days']}" if a else "—"
    L.append(f"| {nm} | {pc(e['coverage'])} | {ci(e)} | {f(e['mean_width'])} | {att} | {rng} | {bd} |")
L += ["", "Burst runs attack only three pre-specified 10-day windows (test days 20–29, 80–89, 140–149) with the worst fixed variant "
      "from the oracle grid; coverage on attacked days is what an attacker who concentrates on the days they trade would face."]

L += ["", "## Soundness checks of the certificate", "",
      f"- Degenerate box reproduces the model exactly: max |error| = {s['degenerate_box_max_abs_err']:.2e}",
      f"- Certificate's feature recomputation matches the aggregator: max |error| = {s['feature_recompute_max_abs_err']:.2e}",
      f"- Clean features lie inside the box computed from attacked documents: {100 * p['clean_features_inside_box_frac']:.2f}% of test rows",
      f"- Own symmetric CQR vs MAPIE `symmetric_correction=True`: max |diff| = {m['own_vs_mapie_symmetric_cqr_max_abs_diff']:.2e}",
      "- Unit tests (`tests/`): deletion box sound and exact vs brute force; tree bounds sound; trust deletion- and injection-stable; "
      "ACI long-run bound |mean err − α| ≤ (max(α, 1−α) + γ)/(γT) on adversarial sequences; ACI boundary cases (whole line / empty set).", "",
      "## Caveats",
      "- One seed and one fixed 87-stock universe (StockNet; survivorship). VADER scorer unless stated.",
      "- Adjusted closes are back-adjusted for dividends and splits; we use only return ratios, so levels do not leak, but volume is not split-adjusted.",
      "- The certificate assumes clean calibration data and covers injection of up to k documents; edits of real documents and price manipulation are out of scope.",
      "- This test period has been looked at several times during development; the untouched-data text-utility test is "
      "`eval/results/text_utility_djia_v1.json` (pre-registered)."]
Path(f"eval/results/{TAG}.md").write_text("\n".join(L) + "\n")
print("\n".join(L[:12]))
