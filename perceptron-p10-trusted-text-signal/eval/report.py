"""Render eval/results/<tag>.json as Markdown: PYTHONPATH=. .venv/bin/python eval/report.py [tag]"""
import json
import sys
from pathlib import Path

TAG = sys.argv[1] if len(sys.argv) > 1 else "baseline_v0"
r = json.loads(Path(f"eval/results/{TAG}.json").read_text())
m = r["meta"]
L = [f"# {TAG} — StockNet, time-ordered split (generated by `eval/report.py` from `{TAG}.json`)", "",
     f"Train {m['train'][0]}→{m['train'][1]} ({m['n_train']:,} ticker-days) · calibration {m['cal'][0]}→{m['cal'][1]} ({m['n_cal']:,}) · "
     f"test {m['test'][0]}→{m['test'][1]} ({m['n_test']:,}) · {m['tickers']} tickers · α = {m['alpha']} (target coverage 90%) · seed {m['seed']} · "
     f"text scorer: {m['text_scorer']} · y = next-day log return in % (width in percentage points) · runtime {m['runtime_s']} s.", "",
     "Reproduce: `bash eval/fetch_data.sh && PYTHONPATH=. .venv/bin/python eval/prepare.py && PYTHONPATH=. .venv/bin/python eval/run_baselines.py`", "",
     "## Ablation × conformal method (clean test data)", "",
     "| Model | Method | Coverage | Mean width | Winkler | Kupiec p | Christoffersen p | Worst-day cov. | Cov. high-vol | Cov. low-vol | Cov. 5+ tweets |",
     "|---|---|---|---|---|---|---|---|---|---|---|"]
f = lambda x: f"{x:.3f}"
pc = lambda x: f"{100*x:.1f}%"
for name, a in r["ablation"].items():
    for meth in ["split", "cqr_mapie", "cqr_aci"]:
        e = a[meth]
        L.append(f"| {name} | {meth} | {pc(e['coverage'])} | {f(e['mean_width'])} | {f(e['winkler'])} | {e['kupiec_p']:.3g} | {e['christoffersen_p']:.3g} | {pc(e['worst_day_coverage'])} | {pc(e['cov[vol=high]'])} | {pc(e['cov[vol=low]'])} | {pc(e['cov[tweets=5+]'])} |")
L += ["", "| Model | Mean pinball (3 quantiles) | Spearman IC (median vs y) | IC on tweet days |", "|---|---|---|---|"]
for name, a in r["ablation"].items():
    L.append(f"| {name} | {a['pinball_mean']:.4f} | {a['ic_spearman']:.4f} | {a['ic_spearman_tweet_days']:.4f} |")
s = r["spike"]
L += ["", "## Spike: certified CQR (fusion model), clean test data — price of robustness", "",
      "| Budget k | Coverage | Mean width | Width vs CQR (k = 0) | Cov. high-vol |", "|---|---|---|---|---|"]
base_w = r["ablation"]["fusion"]["cqr_sym"]["mean_width"]
L.append(f"| 0 (plain symmetric CQR) | {pc(r['ablation']['fusion']['cqr_sym']['coverage'])} | {f(base_w)} | — | {pc(r['ablation']['fusion']['cqr_sym']['cov[vol=high]'])} |")
for k in (1, 2, 3, 5):
    e = s[f"clean_k{k}"]
    L.append(f"| {k} | {pc(e['coverage'])} | {f(e['mean_width'])} | +{100*(e['mean_width']/base_w-1):.1f}% | {pc(e['cov[vol=high]'])} |")
o, p = r["attack"]["oracle"], r["attack"]["pump"]
L += ["", "## Attacks (budget k = 3 injected documents per ticker-day, every test ticker-day attacked)", "",
      "| Scenario | Method | Coverage | Mean width |", "|---|---|---|---|",
      *([] if o.get("skipped") else [
      f"| none | CQR | {pc(o['clean_cqr_coverage'])} | {f(o['vanilla_clean_width'])} |",
      f"| oracle (worst of {o['n_variants']} variants, knows y) | CQR | {pc(o['vanilla_cqr_adversarial_coverage'])} | — |",
      f"| oracle | certified CQR (k = 3) | {pc(o['certified_adversarial_coverage'])} | {f(o['certified_clean_width'])} (clean) |"]),
      f"| pump (sentiment {p['pump_sentiment']:.3f}, trust {p['pump_trust']}) | CQR | {pc(p['vanilla_cqr']['coverage'])} | {f(p['vanilla_cqr']['mean_width'])} |",
      f"| pump | certified CQR (k = 3) | {pc(p['certified']['coverage'])} | {f(p['certified']['mean_width'])} |"]
c = s["cr_aci"]
for nm in ["cqr_aci_clean", "cqr_aci_pump", "cr_aci_clean", "cr_aci_pump"]:
    L.append(f"| {'pump' if 'pump' in nm else 'none'} | {'CR-ACI (spike)' if nm.startswith('cr') else 'CQR + ACI'} | {pc(c[nm]['coverage'])} | {f(c[nm]['mean_width'])} |")
L += ["", f"Pump attack moves the median forecast by {p['median_shift_mean']:+.4f} pp on average (95th pct |shift| {p['median_shift_p95_abs']:.4f} pp).", "",
      "## Soundness checks of the certificate", "",
      f"- Degenerate box reproduces the model exactly: max |error| = {s['degenerate_box_max_abs_err']:.2e}",
      f"- Certificate's feature recomputation matches the aggregator: max |error| = {s['feature_recompute_max_abs_err']:.2e}",
      f"- Clean features lie inside the box computed from attacked documents: {100*p['clean_features_inside_box_frac']:.2f}% of test rows",
      f"- Own symmetric CQR vs MAPIE `symmetric_correction=True`: max |diff| = {m['own_vs_mapie_symmetric_cqr_max_abs_diff']:.2e}", "",
      "Caveats: pooled Kupiec/Christoffersen p-values ignore same-day cross-sectional correlation of misses (optimistic). The oracle adversary knows y but searches only 12 extreme injection variants, so plain CQR's true worst-case coverage within the budget can be *lower* than reported; the certified interval instead covers on every row where the clean CQR interval covers, for every attack within the budget (guaranteed floor = the clean CQR coverage on the same rows), and the 12-variant number only illustrates it. StockNet's 87-name universe is fixed (survivorship)."]
Path(f"eval/results/{TAG}.md").write_text("\n".join(L) + "\n")
print("\n".join(L[-30:]))
