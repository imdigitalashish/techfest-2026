"""Typed contracts for every component of the FLN decision-support layer.

Single source of truth for the shapes that flow between components. Components
import from here; nothing else defines cross-component types. Export JSON
Schema with `python -m architecture.contracts.export_schemas`.

Conventions
- Children are never identified by raw PEN/APAAR ID outside the source
  connector (C1): C2 replaces them with a salted pseudonym `ps_<16 hex>`.
- Geography uses LGD codes (state/district/block); schools use the 11-digit
  UDISE+ code.
- Probabilities are in [0, 1]; proportions are fractions, not percentages.
- Every record that crosses a trust boundary carries `Provenance`.
"""
from __future__ import annotations

from datetime import date, datetime
from enum import Enum
from typing import Annotated, Literal, Optional

from pydantic import BaseModel, ConfigDict, Field

SCHEMA_VERSION = "0.1.0"

UdiseCode = Annotated[str, Field(pattern=r"^\d{11}$", description="11-digit UDISE+ school code")]
PseudoId = Annotated[str, Field(pattern=r"^ps_[0-9a-f]{16}$", description="Salted pseudonym of PEN/APAAR")]
Prob = Annotated[float, Field(ge=0.0, le=1.0)]


class _Frozen(BaseModel):
    model_config = ConfigDict(frozen=True, extra="forbid")


# ---------------------------------------------------------------- enums
class Subject(str, Enum):
    LANGUAGE = "language"
    NUMERACY = "numeracy"


class SourceSystem(str, Enum):
    UDISE_PLUS = "udise_plus"            # annual school census (master data, enrolment, teachers)
    STATE_ASSESSMENT = "state_assessment"  # census-style, usually teacher-administered
    CLASSROOM_TOOL = "classroom_tool"    # spot assessments via app / WhatsApp / IVR / OCR
    ORF_APP = "orf_app"                  # AI oral-reading-fluency capture
    PARAKH = "parakh"                    # national sample survey (Grades 3/6/9)
    ASER = "aser"                        # household sample survey (rural)
    AUDIT_RETEST = "audit_retest"        # independent re-test by CRC / DIET trainee / third party
    ATTENDANCE = "attendance"            # daily attendance feeds (state apps)


class Administrator(str, Enum):
    TEACHER = "teacher"
    CRC = "crc"
    THIRD_PARTY = "third_party"
    AI_ORF = "ai_orf"
    SURVEYOR = "surveyor"


class Role(str, Enum):
    TEACHER = "teacher"
    HEAD_TEACHER = "head_teacher"
    SMC = "smc"            # School Management Committee
    CRC = "crc"            # Cluster Resource Centre coordinator
    BRC = "brc"            # Block Resource Centre / block education officer
    DEO = "deo"            # District education officer / DIET
    STATE = "state"        # SCERT / Samagra Shiksha / VSK
    AUDITOR = "auditor"


class AreaLevel(str, Enum):
    SCHOOL = "school"
    CLUSTER = "cluster"
    BLOCK = "block"
    DISTRICT = "district"
    STATE = "state"


class ReadingLevel(int, Enum):
    """ASER-style ordinal reading levels (highest level reached)."""
    BEGINNER = 0
    LETTER = 1
    WORD = 2
    PARAGRAPH = 3   # Std I level text
    STORY = 4       # Std II level text


class MathLevel(int, Enum):
    """ASER-style ordinal arithmetic levels (highest level reached)."""
    BEGINNER = 0
    NUM_1_9 = 1
    NUM_11_99 = 2
    SUBTRACTION = 3
    DIVISION = 4


# ---------------------------------------------------------------- provenance
class Provenance(_Frozen):
    source: SourceSystem
    source_record_id: str
    fetched_at: datetime
    transform: str = Field(description="component.function@version that produced this record")
    licence: Optional[str] = None
    synthetic: bool = Field(False, description="True if generated by the simulator, never real children")


# ---------------------------------------------------------------- C1/C2 canonical master data
class School(_Frozen):
    udise_code: UdiseCode
    name: str
    state_lgd: str
    district_lgd: str
    block_lgd: str
    cluster_id: Optional[str] = None
    management: Literal["government", "aided", "private", "other"]
    rural: bool
    n_teachers: int = Field(ge=0)
    enrolment_by_grade: dict[int, int] = Field(description="grade (0=Balvatika) -> enrolled children")
    single_teacher: bool
    share_sc: Optional[Prob] = None
    share_st: Optional[Prob] = None
    provenance: Provenance


class Student(_Frozen):
    student: PseudoId
    udise_code: UdiseCode
    grade: int = Field(ge=0, le=12)
    gender: Literal["f", "m", "x"]
    social_category: Optional[Literal["sc", "st", "obc", "general"]] = None
    home_language_matches_medium: Optional[bool] = None
    provenance: Provenance


class AttendanceRecord(_Frozen):
    student: PseudoId
    udise_code: UdiseCode
    on: date
    present: bool
    provenance: Provenance


# ---------------------------------------------------------------- C3 competency framework
class Competency(_Frozen):
    code: str = Field(description="e.g. 'L.G3.ORF' (subject.grade.skill)")
    subject: Subject
    grade_target: int = Field(ge=0, le=5, description="grade by whose end the goal should be met (0=Balvatika)")
    label: str
    prerequisites: list[str] = Field(default_factory=list)
    source_ref: str = Field(description="citation to NIPUN Bharat Lakshya Soochi / NCERT learning outcome")


class Item(_Frozen):
    item_id: str
    instrument: SourceSystem
    subject: Subject
    competency_codes: list[str] = Field(min_length=1, description="Q-matrix row")
    max_score: float = 1.0
    irt_a: Optional[float] = Field(None, description="discrimination, if calibrated")
    irt_b: Optional[float] = Field(None, description="difficulty, if calibrated")


# ---------------------------------------------------------------- assessment evidence
class Response(_Frozen):
    student: PseudoId
    udise_code: UdiseCode
    grade: int
    item_id: str
    score: float = Field(ge=0.0)
    administered_by: Administrator
    assessed_on: date
    provenance: Provenance


class AggregateObservation(_Frozen):
    """Area-level published figure (PARAKH / ASER / state report) used as an anchor."""
    source: SourceSystem
    area_level: AreaLevel
    area_code: str
    subject: Subject
    grade: int
    indicator: str = Field(description="e.g. 'pct_reading_std2_text', 'mean_scale_score'")
    value: float
    std_error: Optional[float] = None
    n_sampled: Optional[int] = None
    year: int
    citation: str


# ---------------------------------------------------------------- C4 diagnostic engine
class MasteryEstimate(_Frozen):
    competency_code: str
    p_mastery: Prob
    n_items: int = Field(ge=0)


class ChildDiagnosis(_Frozen):
    student: PseudoId
    udise_code: UdiseCode
    grade: int
    subject: Subject
    level: int = Field(ge=0, le=4, description="ReadingLevel or MathLevel value")
    level_confidence: Prob
    mastery: list[MasteryEstimate]
    next_competency: Optional[str] = Field(None, description="lowest unmastered competency whose prerequisites are mastered")
    meets_grade_goal: Prob = Field(description="P(child meets the NIPUN goal for their grade)")
    method: str
    as_of: date


# ---------------------------------------------------------------- C5 trust / audit engine
class TrustAssessment(_Frozen):
    udise_code: UdiseCode
    subject: Subject
    grade: int
    reported_pct_meeting_goal: Prob
    risk_score: Prob = Field(description="relative risk score in [0, 1]: a rank blend of forensic features, NOT a calibrated probability of inflation")
    flags: list[str] = Field(default_factory=list, description="forensic rules that fired")
    selected_for_audit: bool
    audit_inclusion_prob: Prob = Field(description="for Horvitz-Thompson weighting")
    audited_pct_meeting_goal: Optional[Prob] = None
    adjusted_pct_meeting_goal: Prob = Field(description="audit-calibrated estimate")
    adjusted_se: float = Field(ge=0.0)


# ---------------------------------------------------------------- C6 linking + small-area estimation
class AreaEstimate(_Frozen):
    area_level: AreaLevel
    area_code: str
    subject: Subject
    grade: int
    indicator: str = "pct_meeting_grade_goal"
    estimate: Prob
    ci_low: Prob
    ci_high: Prob
    n_children: int = Field(ge=0)
    method: str
    sources_used: list[SourceSystem]
    suppressed: bool = Field(False, description="True if hidden by disclosure control (C12)")


# ---------------------------------------------------------------- C7 teacher point-of-use
class TeachingGroup(_Frozen):
    label: str
    level: int
    student_refs: list[str] = Field(description="roll numbers or first names, local to the teacher's device")
    activity_ids: list[str]


class TeacherPlan(_Frozen):
    udise_code: UdiseCode
    grade: int
    subject: Subject
    week_of: date
    groups: list[TeachingGroup]
    message_text: str
    channel: Literal["whatsapp", "sms", "ivr", "offline_pwa"]
    language: str = Field(description="ISO 639 code, e.g. 'hi'")
    payload_bytes: int = Field(ge=0)


# ---------------------------------------------------------------- C8 mentoring visit planner
class VisitPlan(_Frozen):
    crc_id: str
    week_of: date
    visits: list[UdiseCode]
    agenda: dict[str, list[str]] = Field(description="udise_code -> what to observe / coach / re-test")
    expected_children_reached: int


# ---------------------------------------------------------------- C9 allocation + policy feedback
class AllocationDecision(_Frozen):
    area_code: str
    resource: Literal["remedial_camp", "teacher_training_slot", "tlm_grant", "volunteer", "crc_visit_days"]
    units: float = Field(ge=0.0)
    expected_additional_children_meeting_goal: float
    equity_weighted_score: float
    rationale: str


# ---------------------------------------------------------------- C11 action ledger
class ActionRecord(_Frozen):
    action_id: str
    kind: Literal["teacher_plan_sent", "plan_acknowledged", "crc_visit", "remedial_camp", "training", "smc_meeting", "audit_retest"]
    area_code: str
    actor_role: Role
    on: date
    linked_ids: list[str] = Field(default_factory=list)


# ---------------------------------------------------------------- C12 governance
class AccessRequest(_Frozen):
    role: Role
    actor_scope: str = Field(description="UDISE code / cluster / block / district / state code the actor is responsible for")
    resource: Literal["child_diagnosis", "teacher_plan", "trust_assessment", "area_estimate", "raw_responses"]
    target_scope: str
    target_level: AreaLevel
    purpose: Literal["remediation", "mentoring", "planning", "audit", "research"]


class AccessDecision(_Frozen):
    allowed: bool
    transform: Literal["none", "pseudonymise", "aggregate", "suppress"]
    reason: str


__all__ = [n for n in dir() if not n.startswith("_")]
