"""Record scripted sessions for the no-backend fallback: demo/data/recorded_live.js (window.RECORDED).

nyc: the July 4th tab as it opens: the fast-forward time-lapse (3 July 00:00 -> 4 July 21:15, a frame every 10
     minutes), then every minute to 24:00 on 4 July, with no injected surge (real demand only).
syn: the stress test: seed 7000, L=1, P=10, the committed best rule for that cell (reactive) vs the planner,
     a x1 surge on zone 12's 2x2 block at 05:00, minutes 04:00-08:00.
index.html replays these only when no backend is reachable (e.g. opened from file://), under a red RECORDED
banner, with clicks disabled. Solve times are dropped because they are not reproducible.

    .venv/bin/python -m demo.record            # (re)write demo/data/recorded_live.js
    .venv/bin/python -m demo.record --check    # exit 1 if the committed recording differs from a fresh one
"""
from __future__ import annotations

import json
import sys

from demo.engine import DATA, LiveRun

OUT = DATA / "recorded_live.js"
SYN_UI = dict(L=1, P=10, rule="auto", brain="mpc-ewma", drift=False, seed=7000)
SHOCK_AT, SHOCK_ZONE, AFTER = 300, 12, 180


def strip_ms(frames: list[dict]) -> list[dict]:
    for f in frames:
        for p in f["panels"]:
            p.pop("ms", None)
    return frames


def record_syn() -> dict:
    run = LiveRun(**SYN_UI).warm()
    snapshot, stats = run.snapshot(), run.stats()
    frames = run.advance(SHOCK_AT - run.t)
    shock = run.shock(SHOCK_ZONE, 1.0)
    frames += run.advance(AFTER)
    return dict(ui=SYN_UI, config=run.describe(), snapshot=snapshot, stats=stats, shocks=[shock],
                frames=strip_ms(frames), final=run.stats())


def record_nyc() -> dict:
    run = LiveRun(scenario="nyc")
    snapshot0 = run.snapshot()
    run.warm(every=10)
    snapshot, stats = run.snapshot(), run.stats()
    frames = run.advance(run.trace.horizon - run.t)
    return dict(config=run.describe(), snapshot0=snapshot0, warm_frames=run.warm_frames, snapshot=snapshot,
                stats=stats, shocks=[], frames=strip_ms(frames), final=run.stats())


def build() -> str:
    rec = dict(generated_by="demo/record.py", nyc=record_nyc(), syn=record_syn())
    return ("// Generated by demo/record.py (committed code). Replayed by index.html only when no backend is reachable.\n"
            "window.RECORDED = " + json.dumps(rec, separators=(",", ":")) + ";\n")


def main() -> None:
    txt = build()
    if "--check" in sys.argv:
        ok = OUT.exists() and OUT.read_text() == txt
        print("recorded_live.js reproduces from committed code" if ok else "recorded_live.js is STALE: rerun demo.record")
        raise SystemExit(0 if ok else 1)
    OUT.write_text(txt)
    rec = json.loads(txt.split("=", 1)[1].rstrip().rstrip(";"))
    print(f"wrote {OUT.name} ({len(txt) / 1024:.0f} KB); NYC window lost (reactive, planner) = "
          f"{rec['nyc']['final']['event']['lost']}; synthetic surge window lost (rule, planner) = {rec['syn']['final']['shocks'][0]['lost']}")


if __name__ == "__main__":
    main()
