"""Record scripted sessions for the no-backend fallback: demo/data/recorded_live.js (window.RECORDED).

nyc_reference:   the July 4th opening: the unperturbed reference run (replicate 200), its fast-forward time-lapse
                 (3 July 00:00 -> 4 July 21:15, a frame every 10 minutes), then every minute to 24:00 on 4 July.
nyc_interactive: a recorded turn: real demand plus one x1 synthetic surge on the 2x2 block at cell 7 (Midtown
                 Center) from 21:15 on 4 July, every minute to 24:00 (the surge is cut at midnight: 165 of 360 min).
syn:             the stress test: seed 7000, L=1, P=10, the committed best rule for that cell (reactive) vs the
                 planner, a 12-hour city as in phase-v2, a x1 surge on zone 12's 2x2 block at 05:00, then 4 hours.
week:            the 7-day recompute (long-week, seed 200: greedy, reactive, planner), a frame every 30 minutes, and
                 its summary (metrics and the check against eval/results/long-week-v2/episodes.csv), no wall time.
index.html replays these only when no backend is reachable (opened from file://) or when the presenter picks
"Open recorded fallback", under a red RECORDED banner, with clicks disabled. Solve times are dropped (not
reproducible).

    nice -n 10 .venv/bin/python -m demo.record            # (re)write demo/data/recorded_live.js (~1-2 min)
    nice -n 10 .venv/bin/python -m demo.record --check    # exit 1 if the committed recording differs from a fresh one
"""
from __future__ import annotations

import json
import sys

from demo.engine import DATA, BatchRun, LiveRun

OUT = DATA / "recorded_live.js"
SYN_UI = dict(L=1, P=10, rule="auto", brain="mpc-ewma", drift=False, seed=7000)
SYN_ZONE, SYN_AFTER = 12, 240
NYC_ZONE = 7
WEEK_EVERY = 30


def strip_ms(frames: list[dict]) -> list[dict]:
    for f in frames:
        for p in f["panels"]:
            p.pop("ms", None)
    return frames


def record_nyc_reference() -> dict:
    run = LiveRun(scenario="nyc", role="reference")
    snapshot0 = run.snapshot()
    run.warm(every=10)
    snapshot, stats = run.snapshot(), run.stats()
    frames = run.advance(run.trace.horizon - run.t)
    return dict(config=run.describe(), snapshot0=snapshot0, warm_frames=run.warm_frames, snapshot=snapshot,
                stats=stats, shocks=[], frames=strip_ms(frames), final=run.stats())


def record_nyc_interactive() -> dict:
    run = LiveRun(scenario="nyc", role="interactive").warm()
    snapshot, stats = run.snapshot(), run.stats()
    shock = run.shock(NYC_ZONE, 1.0)
    frames = run.advance(run.trace.horizon - run.t)
    return dict(config=run.describe(), snapshot=snapshot, stats=stats, shocks=[shock], frames=strip_ms(frames),
                final=run.stats())


def record_syn() -> dict:
    run = LiveRun(**SYN_UI).warm()
    snapshot, stats = run.snapshot(), run.stats()
    shock = run.shock(SYN_ZONE, 1.0)
    frames = run.advance(SYN_AFTER)
    return dict(ui=SYN_UI, config=run.describe(), snapshot=snapshot, stats=stats, shocks=[shock],
                frames=strip_ms(frames), final=run.stats())


def record_week() -> dict:
    r = BatchRun("week", 200, show=("greedy", "reactive", "mpc-ewma"))
    r.run()
    if r.error:
        raise RuntimeError(r.error)
    summary = {k: v for k, v in r.summary.items() if k != "wall_s"}
    return dict(T=r.T, frames=[f for f in r.frames if f["t"] % WEEK_EVERY == WEEK_EVERY - 1], summary=summary)


def build() -> str:
    rec = dict(generated_by="demo/record.py", nyc_reference=record_nyc_reference(),
               nyc_interactive=record_nyc_interactive(), syn=record_syn(), week=record_week())
    return ("// Generated by demo/record.py (committed code). Replayed by index.html only without a backend.\n"
            "window.RECORDED = " + json.dumps(rec, separators=(",", ":")) + ";\n")


def main() -> None:
    txt = build()
    if "--check" in sys.argv:
        ok = OUT.exists() and OUT.read_text() == txt
        print("recorded_live.js reproduces from committed code" if ok else "recorded_live.js is STALE: rerun demo.record")
        raise SystemExit(0 if ok else 1)
    OUT.write_text(txt)
    rec = json.loads(txt.split("=", 1)[1].rstrip().rstrip(";"))
    ref, it, syn, wk = rec["nyc_reference"], rec["nyc_interactive"], rec["syn"], rec["week"]
    print(f"wrote {OUT.name} ({len(txt) / 1024:.0f} KB)\n"
          f"  nyc_reference   window lost (reactive, planner) = {ref['final']['event']['lost']}\n"
          f"  nyc_interactive window lost (reactive, planner) = {it['final']['event']['lost']}; surge "
          f"{it['shocks'][0]['minutes']} of {it['shocks'][0]['full_minutes']} min\n"
          f"  syn             surge 120-min lost (rule, planner) = {syn['final']['shocks'][0]['lost']}\n"
          f"  week            {len(wk['frames'])} frames; matches the committed metrics: {wk['summary']['parity_all']}")


if __name__ == "__main__":
    main()
