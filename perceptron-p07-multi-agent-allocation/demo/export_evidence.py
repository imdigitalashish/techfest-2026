"""Copy the committed evidence the demo shows into demo/data/evidence.js (window.EVIDENCE), with sources.

Every number shown on screen that is not computed live comes from here. Table cells are copied verbatim (strings)
from the committed result files; per-seed values come from the committed episodes.csv files; the few derived
values (means of committed per-seed values) are labelled "derived" with the file they come from.

    .venv/bin/python -m demo.export_evidence            # (re)write demo/data/evidence.js
    .venv/bin/python -m demo.export_evidence --check    # exit 1 if evidence.js is stale (used by demo/smoke.sh)
"""
from __future__ import annotations

import csv
import hashlib
import json
import re
import sys
from collections import defaultdict
from pathlib import Path

P7 = Path(__file__).resolve().parents[1]
OUT = Path(__file__).resolve().parent / "data" / "evidence.js"
R = "eval/results/"
FILES = {
    "confirm": R + "mvp-v2/confirm.md",
    "phase": R + "phase-v2/summary.md",
    "phasec": R + "phase-v2c/summary.md",
    "week": R + "long-week-v2/summary.md",
    "month": R + "long-month-v2/summary.md",
    "nyc": R + "nyc-v2/summary.md",
    "nycb": R + "nyc-v2b/summary.md",
    "pareto": R + "pareto-v2/summary.md",
    "trust": R + "trust-v2/summary.md",
    "prereg": "eval/preregistration.md",
    "replay": "research/components/real-trace-replay.md",
}
CSVS = {"mvp": R + "mvp-v2/episodes.csv", "phase": R + "phase-v2/episodes.csv", "trust": R + "trust-v2/episodes.csv",
        "nyc": R + "nyc-v2/episodes.csv", "week": R + "long-week-v2/episodes.csv",
        "cells": "components/scenarios/nyc_zone_to_cell.csv", "phase_summary": R + "phase-v2/phase_summary.csv"}


def cells(line: str) -> list[str]:
    return [c.strip() for c in line.strip().strip("|").split("|")]


def md_tables(rel: str) -> list[dict]:
    lines = (P7 / rel).read_text().splitlines()
    out, heading, caption, i = [], "", "", 0
    while i < len(lines):
        ln = lines[i]
        if ln.startswith("#"):
            heading, caption = ln.lstrip("#").strip(), ""
        elif ln.startswith("|") and i + 1 < len(lines) and re.fullmatch(r"\|[-|: ]+\|", lines[i + 1].strip()):
            header, rows = cells(ln), []
            i += 2
            while i < len(lines) and lines[i].startswith("|"):
                rows.append(cells(lines[i]))
                i += 1
            out.append(dict(heading=heading, caption=caption, header=header, rows=rows))
            continue
        elif ln.strip():
            caption = ln.strip()
        i += 1
    return out


def table(tabs: list[dict], key: str) -> dict:
    hits = [t for t in tabs if key in t["heading"] or key in t["caption"] or key in " | ".join(t["header"])]
    if len(hits) != 1:
        raise KeyError(f"table {key!r}: {len(hits)} matches")
    return hits[0]


def row(t: dict, **match) -> dict:
    hits = [dict(zip(t["header"], r)) for r in t["rows"]]
    hits = [h for h in hits if all(h.get(k) == v for k, v in match.items())]
    if len(hits) != 1:
        raise KeyError(f"row {match}: {len(hits)} matches in {t['heading']!r}")
    return hits[0]


def read_csv(rel: str) -> list[dict]:
    with open(P7 / rel) as f:
        return list(csv.DictReader(f))


def per_seed(rows: list[dict], key: tuple[str, ...], fields: tuple[str, ...]) -> dict:
    """{'k1|k2': {'seed': [...], field: [...]}} sorted by seed (episodes are paired by seed: CRN)."""
    acc: dict = defaultdict(list)
    for r in rows:
        acc["|".join(r[k] for k in key)].append(r)
    out = {}
    for k, rs in sorted(acc.items()):
        rs.sort(key=lambda r: int(r["seed"]))
        d = {"seed": [int(r["seed"]) for r in rs]}
        for f in fields:
            d[f] = [json.loads(r[f]) if f == "daily_served" else float(r[f]) for r in rs]
        out[k] = d
    return out


def build() -> dict:
    T = {k: md_tables(v) for k, v in FILES.items()}
    src = {k: dict(path=v, sha1=hashlib.sha1((P7 / v).read_bytes()).hexdigest()[:12])
           for k, v in {**FILES, **{"csv_" + k: v for k, v in CSVS.items()}}.items()}
    ev: dict = dict(note="Generated by demo/export_evidence.py from committed files; cells copied verbatim.",
                    sources=src, claims={}, tables={})
    c = ev["claims"]

    # pre-registered confirmatory test (mvp-v2)
    conf = T["confirm"]
    c["prereg_header"] = dict(text=(P7 / FILES["confirm"]).read_text().splitlines()[2], src="confirm")
    prim = table(conf, "Primary family")
    c["prereg"] = {r[0]: dict(zip(prim["header"], r)) for r in prim["rows"]}
    s1 = table(conf, "Secondary family S1 — served_frac")
    s1l = table(conf, "Secondary family S1 — shock_lost")
    s3 = table(conf, "Secondary family S3 — served_frac")
    c["queue_shock_pp"] = row(s1, scenario="shock", comparison="mpc-queue − mpc-ewma")
    c["queue_shock_lost"] = row(s1l, scenario="shock", comparison="mpc-queue − mpc-ewma")
    c["oracle_shock_pp"] = row(s3, scenario="shock", comparison="oracle − mpc-ewma")
    mv = table(conf, "Movement cost and shock recovery")
    c["movement"] = [dict(zip(mv["header"], r)) for r in mv["rows"] if r[0] in ("shock", "shock+drift")]
    served = table(conf, "Served fraction by policy")
    c["served_by_policy"] = {r[0]: dict(zip(served["header"], r)) for r in served["rows"]}

    # (L, P) map (phase-v2), its lost-per-shock table and the pre-registered H1 family
    ph = T["phase"]
    main = table(ph, "best rule (served) | mpc-ewma")
    lost = table(ph, "Requests lost in the 120 steps after shock onset")
    h1 = table(ph, "Pre-registered H1 family")
    c["phase_header"] = dict(text=(P7 / FILES["phase"]).read_text().splitlines()[2], src="phase")
    c["phase"] = {f"{r[0]},{r[1]}": dict(main=dict(zip(main["header"], r)), lost=row(lost, L=r[0], P=r[1]),
                                         h1=row(h1, L=r[0], P=r[1])) for r in main["rows"]}
    with open(P7 / CSVS["phase_summary"]) as f:
        c["phase_best_rule"] = {f"{r['L']},{r['P']}": r["best_rule"] for r in csv.DictReader(f)}

    # long horizons
    wk = T["week"]
    c["week_policy"] = {r[0]: dict(zip(table(wk, "served fraction [95% CI over seeds]")["header"], r))
                        for r in table(wk, "served fraction [95% CI over seeds]")["rows"]}
    c["week_cmp"] = row(table(wk, "Δ served (pp) [95% paired CI]"), comparison="mpc-ewma − reactive")
    day = table(wk, "Per-day served fraction")
    c["week_days"] = {r[0]: dict(zip(day["header"], r)) for r in day["rows"]}
    c["week_header"] = dict(text=(P7 / FILES["week"]).read_text().splitlines()[2], src="week")
    c["month_cmp"] = row(table(T["month"], "Δ served (pp) [95% paired CI]"), comparison="mpc-ewma − reactive")

    # NYC replay
    ny = T["nyc"]
    c["nyc_header"] = dict(text=(P7 / FILES["nyc"]).read_text().splitlines()[2], src="nyc")
    c["nyc_policy"] = {r[0]: dict(zip(table(ny, "event_lost")["header"], r)) for r in table(ny, "event_lost")["rows"]}
    c["nyc_cmp"] = row(table(ny, "Δ event lost"), comparison="mpc-ewma − reactive")
    c["nycb_cmp"] = row(table(T["nycb"], "Δ served (pp) [95% paired CI]"), comparison="mpc-ewma − reactive")
    surges = table(T["replay"], "Top July 4 surges")
    c["nyc_surge"] = row(surges, rank="1")
    m = re.search(r"q = (0\.\d+)", (P7 / FILES["replay"]).read_text())
    c["nyc_q"] = dict(text=m.group(1), src="replay")
    nyc_rows = read_csv(CSVS["nyc"])
    ev_lost: dict = defaultdict(list)
    for r in nyc_rows:
        ev_lost[r["policy"]].append(float(r["event_lost"]))
    c["nyc_event_lost_mean"] = {p: dict(text=f"{sum(v) / len(v):.2f}", n=len(v), src="csv_nyc",
                                        how="derived: mean of event_lost over the committed replicates")
                                for p, v in sorted(ev_lost.items())}
    names: dict = defaultdict(list)
    for r in read_csv(CSVS["cells"]):
        names[int(r["cell"])].append(r["zone_name"])
    c["nyc_cells"] = {str(k): v for k, v in sorted(names.items())}

    # movement cost, forecast trust
    c["pareto_cmp"] = row(table(T["pareto"], "Δ empty hops / served"), comparison="mpc-ewma@c_move=0.5 − reactive")
    tr = table(T["trust"], "best − max(trust 0, trust 1)")
    c["trust"] = {r[0]: dict(zip(tr["header"], r)) for r in tr["rows"]}
    ref = table(T["prereg"], "Reference rule per scenario")
    c["prereg_reference"] = {r[0]: dict(zip(ref["header"], r)) for r in ref["rows"]}

    # per-seed values for the "your shock is seed #21" strip (paired by seed)
    ev["seeds"] = dict(
        phase=per_seed(read_csv(CSVS["phase"]), ("hop_steps", "patience", "policy"), ("shock_lost", "served_frac")),
        mvp=per_seed([r for r in read_csv(CSVS["mvp"]) if r["scenario"] in ("shock", "shock+drift")],
                     ("scenario", "policy"), ("shock_lost", "served_frac")),
        trust=per_seed([r for r in read_csv(CSVS["trust"]) if r["scenario"] in ("shock", "shock+drift")],
                       ("scenario", "policy"), ("shock_lost", "served_frac")),
        nyc=per_seed(nyc_rows, ("policy",), ("event_lost", "served_frac")),
        week=per_seed(read_csv(CSVS["week"]), ("policy",), ("daily_served", "served_frac")))

    # verbatim tables for the Evidence tab
    ev["tables"] = {k: [dict(t, src=k) for t in T[k]] for k in ("confirm", "phase", "phasec", "week", "nyc", "nycb",
                                                                   "pareto", "trust")}
    ev["tables"]["month"] = [dict(t, src="month") for t in T["month"] if "Per-day" not in t["heading"]]
    return ev


def render(ev: dict) -> str:
    return "// Generated by demo/export_evidence.py from committed result files. Do not edit by hand.\n" \
           "window.EVIDENCE = " + json.dumps(ev, ensure_ascii=False, separators=(",", ":")) + ";\n"


def main() -> None:
    txt = render(build())
    if "--check" in sys.argv:
        ok = OUT.exists() and OUT.read_text() == txt
        print("evidence.js matches the committed result files" if ok else "evidence.js is STALE: rerun demo.export_evidence")
        raise SystemExit(0 if ok else 1)
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(txt)
    print(f"wrote {OUT.relative_to(P7)} ({len(txt) / 1024:.0f} KB)")


if __name__ == "__main__":
    main()
